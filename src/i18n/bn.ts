export const BANGLA_NUMERALS: Record<string, string> = {
  '0': '০',
  '1': '১',
  '2': '২',
  '3': '৩',
  '4': '৪',
  '5': '৫',
  '6': '৬',
  '7': '৭',
  '8': '৮',
  '9': '৯',
};

export function toBanglaNumeral(val: number | string): string {
  const str = String(val);
  return str.replace(/[0-9]/g, (digit) => BANGLA_NUMERALS[digit] || digit);
}

